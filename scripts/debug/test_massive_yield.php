    }

    $articles = [];
    foreach ($urls as $u) {
        $res = Http::withHeaders(['User-Agent' => 'Mozilla/5.0'])->timeout(5)->get($u);
        $xml = @simplexml_load_string($res->body());
        if ($xml && isset($xml->channel->item)) {
            foreach ($xml->channel->item as $item) {
                $mapped = GoogleNewsRss::mapRssItem($item);
                if ($mapped && !isset($articles[$mapped['link']])) {
                    $articles[$mapped['link']] = $mapped;
                }
            }
        }
    }

    $passed = [];
    foreach ($articles as $a) {
        if (matchTopicStrictLocal($a['title'], $a['description'], $data['positives'], $data['negatives'])) {
            $passed[] = $a;
        }
    }

